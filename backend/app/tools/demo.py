"""Run each registered tool once and print its result envelope."""

from __future__ import annotations

import asyncio
import json
import sys

from app.db.session import SessionLocal
from app.tools.registry import build_default_registry


async def main() -> None:
    """Invoke the default tools once each, including clean DB-unavailable results."""
    async with SessionLocal() as session:
        registry = build_default_registry(session=session)
        requests = {
            "document_search": {"query": "regional revenue target", "top_k": 3},
            "csv_reader": {"operation": "describe", "filename": "sales_2025.csv"},
            "calculator": {"expression": "pct_change(100, 115)"},
            "report_generator": {
                "title": "ResearchPilot Demo",
                "executive_summary": "A local report generated by the controlled tool registry.",
                "sections": [
                    {
                        "heading": "Execution",
                        "body": "The tool envelope validates the structured report draft.",
                        "evidence_refs": [],
                    }
                ],
                "findings": [],
                "recommendations": ["Review source evidence before acting."],
                "limitations": ["This demo does not invoke the research agent."],
                "appendix_tables": [],
            },
        }
        for name, payload in requests.items():
            result = await registry.get(name).execute(payload)
            sys.stdout.write(
                json.dumps({"tool": name, **result.model_dump(mode="json")}, indent=2)
                + "\n"
            )


if __name__ == "__main__":
    asyncio.run(main())
